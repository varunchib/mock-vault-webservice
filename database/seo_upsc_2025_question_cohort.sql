## Correct answer: Only one

Only the **Inter-State Council** is established under a provision of the Constitution.

**Inter-State Council — constitutional.** Article 263 allows the President to establish an Inter-State Council when it appears that a body is needed to investigate, discuss or recommend on matters of common interest between the Union and States.

**National Security Council — not constitutional.** It is an executive body, not one created by a constitutional article.

**Zonal Councils — not constitutional.** They were created under the **States Reorganisation Act, 1956**, which is an Act of Parliament.

The test is the source of authority: Article 263 for the Inter-State Council, executive/statutory sources for the other two. Hence **Only one (Option A)** is correct.

