## Correct answer: The Poona Pact

The relevant event is the **Poona Pact of September 1932**. It followed the dispute over separate electorates for the Depressed Classes and was concluded between M. K. Gandhi and B. R. Ambedkar while Gandhi was fasting in Yerwada jail.

The pact provided for reserved seats for the Depressed Classes within a joint electorate. After this period, Gandhi made work against untouchability a major part of his public programme and supported organisations and campaigns connected with the upliftment of the communities he then referred to as “Harijans.”

The other options are from different phases of the national movement and do not explain this specific shift in Gandhi's social programme. Therefore, **The Poona Pact (Option A)** is correct.

