## Correct answer: Mahendravarman I

The titles **Mattavilasa**, **Vichitrachitta** and **Gunabhara** are associated with **Mahendravarman I**, a Pallava ruler who ruled from Kanchipuram in the early seventh century CE.

The identification is strengthened by two useful clues. Mahendravarman I is associated with the Sanskrit farce *Mattavilasa Prahasana* and with early Pallava rock-cut architecture. The Mandagapattu inscription is commonly used to discuss his patronage of a temple made without the usual brick, timber, metal or mortar.

Do not confuse him with **Simhavishnu**, his predecessor, or **Narasimhavarman I (Mamalla)**, who is associated with later Pallava achievements and Mamallapuram.

For this question, match the cluster of titles—not merely the dynasty—to **Mahendravarman I (Option A)**.

