In common lithium-ion EV battery chemistries, **lithium, nickel and cobalt** are associated with the cathode. For example, nickel-manganese-cobalt (NMC) and nickel-cobalt-aluminium (NCA) cathodes use these materials in their cathode compounds.

**Graphite** is the exception in this list. It is most commonly used for the **anode**, the electrode that stores lithium during charging in conventional lithium-ion cells.

