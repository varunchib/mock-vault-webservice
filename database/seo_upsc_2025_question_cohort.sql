## Correct answer: India to Central Asia to Europe via Iran

The **International North-South Transport Corridor (INSTC)** is a multimodal route using sea, rail and road links. Its central geographic feature is **Iran**, which connects Indian maritime routes with overland and Caspian routes towards Central Asia, Russia and Europe.

India is a founding member of the INSTC agreement. In broad terms, the corridor links India with Iran and then onward through routes involving the Caspian region, Central Asia, Russia and Europe.

Option A is therefore the best description: **India to Central Asia to Europe via Iran**. The other options describe different regional connectivity ideas or omit the corridor's defining Iran link.

