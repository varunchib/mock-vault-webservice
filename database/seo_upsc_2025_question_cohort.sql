## Correct answer: I, II and V

The RBI earns income from central-banking operations; it is not a commercial lender or a public pension-fund manager.

**I. Government securities — correct.** In open-market operations the RBI buys and sells government securities. Interest earned on securities it holds is part of its income.

**II. Foreign-exchange operations — correct.** The RBI manages India's foreign-exchange reserves. Income can arise from foreign assets and related reserve-management operations.

**III. Pension-fund management — incorrect.** Managing pension funds for the public is not an RBI income function.

**IV. Lending to private companies — incorrect.** The RBI's lending role is primarily to banks and governments; it does not operate as a direct lender to private companies.

**V. Currency issuance — correct in this question's context.** Currency issuance produces seigniorage: the gap between a note's face value and the cost associated with issuing it.

Therefore, the correct combination is **I, II and V (Option D)**.

